const testPostgresDSNEnv = "AGENT_COMPOSE_TEST_POSTGRES_DSN"

func TestPostgresConnectorIntegration(t *testing.T) {
	baseDSN := strings.TrimSpace(os.Getenv(testPostgresDSNEnv))
	if baseDSN == "" {
		t.Skipf("set %s to run PostgreSQL integration tests", testPostgresDSNEnv)
	}

	ctx, cancel := context.WithTimeout(context.Background(), 30*time.Second)
	defer cancel()

	admin, err := openDB(baseDSN)
	if err != nil {
		t.Fatalf("open admin database: %v", err)
	}
	t.Cleanup(func() { _ = admin.Close() })

	schema := fmt.Sprintf("ac_test_%d", time.Now().UnixNano())
	if _, err := admin.ExecContext(ctx, "CREATE SCHEMA "+schema); err != nil {
		t.Fatalf("create schema: %v", err)
	}
	t.Cleanup(func() {
		cleanupCtx, cleanupCancel := context.WithTimeout(context.Background(), 10*time.Second)
		defer cleanupCancel()
		if _, err := admin.ExecContext(cleanupCtx, "DROP SCHEMA "+schema+" CASCADE"); err != nil {
			t.Logf("drop schema %s: %v", schema, err)
		}
	})

	db, err := openDB(withSearchPath(baseDSN, schema))
	if err != nil {
		t.Fatalf("open schema database: %v", err)
	}
	defer func() { _ = db.Close() }()
	db.SetMaxOpenConns(4)

	if err := db.PingContext(ctx); err != nil {
		t.Fatalf("ping: %v", err)
	}
	var currentSchema string
	if err := db.QueryRowContext(ctx, `SELECT current_schema()`).Scan(&currentSchema); err != nil {
		t.Fatalf("read current schema: %v", err)
	}
	if currentSchema != schema {
		t.Fatalf("current schema = %q, want %q", currentSchema, schema)
	}
	if _, err := db.ExecContext(ctx, `
		CREATE TABLE sample (
			id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
			name TEXT NOT NULL,
			enabled BIGINT NOT NULL DEFAULT 0,
			created_at BIGINT NOT NULL
		);
		CREATE INDEX sample_name ON sample(name);
	`); err != nil {
		t.Fatalf("apply multi-statement schema: %v", err)
	}

	var sequence int64
	if err := db.QueryRowContext(ctx,
		`INSERT INTO sample(name, enabled, created_at) VALUES(?, ?, ?) RETURNING id`,
		"first", 1, int64(1)<<40).Scan(&sequence); err != nil {
		t.Fatalf("insert with returning: %v", err)
	}
	if sequence != 1 {
		t.Fatalf("sequence = %d, want 1", sequence)
	}

	var (
		name      string
		enabled   int
		createdAt int64
	)
	if err := db.QueryRowContext(ctx,
		`SELECT name, enabled, created_at FROM sample WHERE id = ? AND name = ?`,
		sequence, "first").Scan(&name, &enabled, &createdAt); err != nil {
		t.Fatalf("query with placeholders: %v", err)
	}
	if name != "first" || enabled != 1 || createdAt != int64(1)<<40 {
		t.Fatalf("row = (%q, %d, %d)", name, enabled, createdAt)
	}

	var literal string
	if err := db.QueryRowContext(ctx, `SELECT '?' || ?`, "x").Scan(&literal); err != nil {
		t.Fatalf("query with literal question mark: %v", err)
	}
	if literal != "?x" {
		t.Fatalf("literal = %q, want ?x", literal)
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		t.Fatalf("begin tx: %v", err)
	}
	if _, err := tx.ExecContext(ctx, `INSERT INTO sample(name, enabled, created_at) VALUES(?, 0, 0)`, "rollback"); err != nil {
		t.Fatalf("insert in tx: %v", err)
	}
	if err := tx.Rollback(); err != nil {
		t.Fatalf("rollback: %v", err)
	}
	var count int
	if err := db.QueryRowContext(ctx, `SELECT COUNT(*) FROM sample`).Scan(&count); err != nil {
		t.Fatalf("count: %v", err)
	}
	if count != 1 {
		t.Fatalf("count = %d, want 1 after rollback", count)
	}

	stmt, err := db.PrepareContext(ctx, `SELECT name FROM sample WHERE id = ?`)
	if err != nil {
		t.Fatalf("prepare: %v", err)
	}
	defer func() { _ = stmt.Close() }()
	if err := stmt.QueryRowContext(ctx, sequence).Scan(&name); err != nil {
		t.Fatalf("prepared query: %v", err)
	}
	if name != "first" {
		t.Fatalf("prepared name = %q", name)
	}

	assertAdvisoryLock(t, ctx, db)
}

func assertAdvisoryLock(t *testing.T, ctx context.Context, db *sql.DB) {
	t.Helper()
	const key = int64(0x61632d70672d6c6b) // arbitrary constant
	holder, err := db.Conn(ctx)
	if err != nil {
		t.Fatalf("acquire lock holder: %v", err)
	}
	defer func() { _ = holder.Close() }()
	var locked bool
	if err := holder.QueryRowContext(ctx, `SELECT pg_try_advisory_lock($1)`, key).Scan(&locked); err != nil {
		t.Fatalf("take advisory lock: %v", err)
	}
	if !locked {
		t.Fatal("first advisory lock was not acquired")
	}
	other, err := db.Conn(ctx)
	if err != nil {
		t.Fatalf("acquire second connection: %v", err)
	}
	defer func() { _ = other.Close() }()
	var second bool
	if err := other.QueryRowContext(ctx, `SELECT pg_try_advisory_lock($1)`, key).Scan(&second); err != nil {
		t.Fatalf("second advisory lock: %v", err)
	}
	if second {
		t.Fatal("second advisory lock succeeded while first was held")
	}
	var unlocked bool
	if err := holder.QueryRowContext(ctx, `SELECT pg_advisory_unlock($1)`, key).Scan(&unlocked); err != nil {
		t.Fatalf("release advisory lock: %v", err)
	}
	if !unlocked {
		t.Fatal("advisory lock was not released")
	}
}

func withSearchPath(dsn, schema string) string {
	separator := "?"
	if strings.Contains(dsn, "?") {
		separator = "&"
	}
	return dsn + separator + "search_path=" + schema
}
